class NonRetryableError(RuntimeError):
    """Ошибка, которую повтор не исправит (видео слишком большое, битый файл, нет настроек).

    Воркер сразу ставит такому ролику failed, не тратя попытки на новый запуск Apify и скачивание.
    """


class ConfigError(NonRetryableError):
    """Сервис не настроен: не задан ключ или адрес внешнего API."""
